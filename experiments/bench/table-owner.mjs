// Runtime table-ownership guard.
//
// scripts/check-table-owners.mjs catches contested tables statically, before a
// release. This is the second line: it refuses, at write time, to overwrite a
// generated table whose header names a different generator. That converts a
// silent overwrite into an immediate, explanatory failure.
//
// Usage:
//   import { writeTable } from '../bench/table-owner.mjs';
//   await writeTable(targetPath, tex, import.meta.url);
//
// Set TABLE_OWNER_OVERRIDE=1 to take ownership deliberately (for example when a
// generator is genuinely being replaced); the override is logged.
import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HEADER = /^%\s*auto-generated by\s+(\S+)/;

/** Repo-relative generator id, e.g. "scripts/gen-tables.mjs". */
export function generatorId(importMetaUrl) {
  const file = fileURLToPath(importMetaUrl);
  const parts = file.split(path.sep);
  const i = parts.lastIndexOf("experiments");
  return i === -1 ? path.basename(file) : parts.slice(i + 1).join("/");
}

/** Owner named by an existing table's header, or null. */
export async function currentOwner(targetPath) {
  if (!existsSync(targetPath)) return null;
  const first = (await readFile(targetPath, "utf8")).split("\n", 1)[0];
  const m = first.match(HEADER);
  return m ? m[1].replace(/^experiments\//, "") : null;
}

/**
 * Write a generated table, refusing to clobber another generator's output.
 * `tex` should already carry its `% auto-generated by ...` header.
 */
export async function writeTable(targetPath, tex, importMetaUrl) {
  const me = generatorId(importMetaUrl);
  const owner = await currentOwner(targetPath);
  if (owner && owner !== me) {
    if (process.env.TABLE_OWNER_OVERRIDE !== "1") {
      throw new Error(
        `refusing to overwrite ${path.basename(targetPath)}: it is generated by ${owner}, not ${me}.\n`
        + `Two generators writing one table means whichever runs last wins, which can replace a\n`
        + `table built from the accepted campaign with one built from a superseded record.\n`
        + `Give this output its own filename and \\label, or set TABLE_OWNER_OVERRIDE=1 to take\n`
        + `ownership deliberately.`,
      );
    }
    console.warn(`table-owner: ${me} is taking ownership of ${path.basename(targetPath)} from ${owner} (override set)`);
  }
  await writeFile(targetPath, tex);
}
