import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const rows = JSON.parse(fs.readFileSync(path.join(root, 'results', 'rq2-campaign2.json'), 'utf8'));
const layers = ['knex', 'drizzle', 'prisma', 'sequelize', 'typeorm', 'objection', 'mikroorm'];
const median = (values) => {
  const xs = [...values].sort((a, b) => a - b);
  const mid = Math.floor(xs.length / 2);
  return xs.length % 2 ? xs[mid] : (xs[mid - 1] + xs[mid]) / 2;
};

const pointLines = [];
const medianLines = [];
let maxCv = 0;
for (const [index, layer] of layers.entries()) {
  const row = rows.find((x) => x.adapter === layer && x.engine === 'mysql' && x.endpoint === 'write');
  if (!row || row.rps_samples.length !== 25) throw new Error(`incomplete MySQL insert cell: ${layer}`);
  const samples = row.rps_samples;
  const mean = samples.reduce((sum, x) => sum + x, 0) / samples.length;
  const sd = Math.sqrt(samples.reduce((sum, x) => sum + (x - mean) ** 2, 0) / (samples.length - 1));
  maxCv = Math.max(maxCv, sd / mean);
  pointLines.push(samples.map((sample) => `(${index + 1},${sample})`).join(' '));
  const m = median(samples);
  medianLines.push(
    `  \\addplot[thick,red,mark=none] coordinates {(${index + 0.72},${m}) (${index + 1.28},${m})};`,
  );
}

const tex = `% auto-generated by experiments/scripts/gen-rq2-insert-figure.mjs
\\begin{figure}[htbp]
  \\centering
  \\begin{tikzpicture}
  \\begin{axis}[width=0.94\\textwidth,height=6cm,
      ylabel={Insert throughput (req/s)}, xmin=0.4, xmax=7.6,
      xtick={1,2,3,4,5,6,7},
      xticklabels={${layers.map((x) => `\\texttt{${x}}`).join(',')}},
      x tick label style={rotate=35,anchor=east,font=\\footnotesize},
      ymajorgrids, tick align=outside]
  \\addplot[only marks,mark=o,mark size=1.1pt,draw=black!55] coordinates {
${pointLines.join('\n')}
  };
${medianLines.join('\n')}
  \\end{axis}
  \\end{tikzpicture}
  \\caption{Corrected-state raw per-replicate MySQL insert throughput for the seven
    portable layers (25 independent repetitions; red bar = median; maximum CV
    ${(100 * maxCv).toFixed(1)}\\%). The points, rather than only medians and intervals,
    expose any mixture or tail structure. Historical insert samples affected by the
    reset defect are not used for the corrected ordering.}
  \\label{fig:insert_dispersion}
\\end{figure}
`;

const outputs = [
  path.join(root, "results", "tables", "fig_insert_dispersion.tex"),
  path.resolve(root, "..", "paper", "tables", "fig_insert_dispersion.tex"),
];
for (const output of outputs) fs.writeFileSync(output, tex);
