// Generate the R4 experiment tables (utilization, cluster, mixed) from their JSON.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const R = (f) => readFile(join(here, '..', 'results', f), 'utf8').then(JSON.parse).catch(() => null);
const out2 = async (name, tex) => { await writeFile(join(here, '..', 'results', 'tables', name), tex); await writeFile(join(here, '..', '..', 'paper', 'tables', name), tex); };

// --- utilization: p99 at each utilization fraction, per layer, per engine -----
for (const engine of ['postgres', 'mysql']) {
  const utilFile = engine === 'postgres'
    ? (process.env.UTIL_PG_FILE || 'utilization-corrected.postgres.json')
    : (process.env.UTIL_MY_FILE || 'utilization-corrected.mysql.json');
  const d = await R(utilFile); if (!d) continue;
  const layers = [...new Set(d.map((x) => x.adapter))];
  const fr = [...new Set(d.map((x) => x.fraction))].sort((a, b) => a - b);
  const rows = layers.map((a) => {
    // Median over 5 runs with the observed min--max, so a 5-replicate cell is not
    // read as a point estimate (these values are quoted in the abstract).
    const cells = fr.map((f) => {
      const r = d.find((x) => x.adapter === a && x.fraction === f);
      if (!r) return '--';
      const s = r.p99_samples;
      if (!Array.isArray(s) || s.length === 0) return String(r.p99_med);
      return `${r.p99_med}~[${Math.min(...s)}--${Math.max(...s)}]`;
    });
    return `    \\texttt{${a}} & ${cells.join(' & ')} \\\\`;
  }).join('\n');
  const eng = engine === 'mysql' ? 'MySQL' : 'PostgreSQL';
  const label = engine === 'postgres' ? 'utilization' : 'utilization_mysql';
  const tex = `% auto-generated by scripts/gen-r4-tables.mjs
\\begin{table}[htbp]
  \\centering
  \\caption{Utilization-controlled open-loop tail on the deep fetch (${eng}):
    coordinated-omission-corrected p99 (ms) when each layer is
    offered a fixed fraction of its $\\widehat C_{50}$ capacity proxy (the 25-run
    median throughput at 50 connections). Cells give the median of five runs with the
    observed minimum--maximum in brackets; with only five replicates the bracket is the
    raw spread, not an interval estimate. The 50\\% and 70\\% columns carry the sub-saturation comparison and are interpreted with the denominator sensitivity in Supplement Table~S45. The 85\\% and 95\\% columns are near-saturation sensitivity evidence, not a precise convergence claim --- as their spreads show directly.}
  \\label{tab:${label}}
  \\begin{tabular}{l ${fr.map(() => 'r').join(' ')}}
    \\toprule
    Layer & ${fr.map((f) => `${Math.round(f * 100)}\\%`).join(' & ')} \\\\
    \\midrule
${rows}
    \\bottomrule
  \\end{tabular}
\\end{table}
`;
  await out2(`${label}.tex`, tex);
}

// --- cluster: rps at 1/2/4 workers, per layer, per engine ---------------------
{
  const d = await R('cluster.json');
  if (d) {
    const workers = [...new Set(d.map((x) => x.workers))].sort((a, b) => a - b);
    const rows = [];
    for (const engine of ['postgres', 'mysql']) {
      const eng = engine === 'mysql' ? 'MySQL' : 'PostgreSQL';
      const layers = [...new Set(d.filter((x) => x.engine === engine).map((x) => x.adapter))];
      rows.push(`    \\multicolumn{${workers.length + 1}}{l}{\\emph{${eng}}} \\\\`);
      for (const a of layers) {
        const cells = workers.map((w) => { const r = d.find((x) => x.engine === engine && x.adapter === a && x.workers === w); return r ? String(r.rps_med) : '--'; });
        rows.push(`    \\quad\\texttt{${a}} & ${cells.join(' & ')} \\\\`);
      }
    }
    const tex = `% auto-generated by scripts/gen-r4-tables.mjs
\\begin{table}[htbp]
  \\centering
  \\caption{Multi-worker deep-fetch throughput (req/s, median of three runs) as each
    layer is scaled to 1, 2, and 4 Express workers (node cluster, shared port). This bounded 1-to-4-worker sensitivity reports aggregate throughput for the
    displayed subset. It does not locate database-side saturation or establish
    scalability beyond four co-located application processes.}
  \\label{tab:cluster}
  \\begin{tabular}{l ${workers.map(() => 'r').join(' ')}}
    \\toprule
    Layer & ${workers.map((w) => `${w}~worker${w > 1 ? 's' : ''}`).join(' & ')} \\\\
    \\midrule
${rows.join('\n')}
    \\bottomrule
  \\end{tabular}
\\end{table}
`;
    await out2('cluster.tex', tex);
  }
}

// --- mixed read/write ---------------------------------------------------------
{
  const d = await R('mixed.json');
  if (d) {
    const rows = d.map((r) => `    ${r.engine === 'mysql' ? 'MySQL' : 'PG'} & \\texttt{${r.adapter}} & ${r.mix} & ${r.rps_med} & ${r.p99_med} \\\\`).join('\n');
    const tex = `% auto-generated by scripts/gen-r4-tables.mjs
\\begin{table}[htbp]
  \\centering
  \\caption{Mixed read/write workload: throughput (req/s) and p99 (ms) under an
    autocannon request mix interleaving the deep-fetch read with single-row inserts,
    at 90:10 and 70:30 read:write, both engines, median of five runs with an exact
    row-and-allocator reset per run. This is an exploratory sensitivity check; its
    observed ordering is interpreted from the displayed cells rather than assumed.}
  \\label{tab:mixed}
  \\begin{tabular}{l l l r r}
    \\toprule
    Engine & Layer & read:write & req/s & p99 \\\\
    \\midrule
${rows}
    \\bottomrule
  \\end{tabular}
\\end{table}
`;
    await out2('mixed.tex', tex);
  }
}
console.log('wrote utilization(.mysql).tex, cluster.tex, mixed.tex');
