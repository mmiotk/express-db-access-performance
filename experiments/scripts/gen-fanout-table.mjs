// Supplement table: native-relative multiplier across deep-fetch fan-out breadth.
//
// The main text asserted a "roughly fixed multiplier rather than a spread that grows
// with breadth". That holds on MySQL and is false on PostgreSQL, where the spread
// widens from about 6x to about 12x as breadth goes 0 -> 500. The claim had no table
// and no cross-reference, so nobody could check it. This generates the evidence.
//
// Multiplier = native median rps / layer median rps at the same fan-out, so 1.0 means
// parity with the native driver and larger means slower. Tuned baselines are excluded:
// they are disclosed reference points, not selected treatments.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const IN = process.env.FANOUT_FILE || 'fanout.json';
const NATIVE = { postgres: 'pg', mysql: 'mysql2' };
const ENGINE_LABEL = { postgres: 'PostgreSQL', mysql: 'MySQL' };

const d = JSON.parse(await readFile(join(here, '..', 'results', IN), 'utf8'));
const fanouts = [...new Set(d.map((x) => x.fanout))].sort((a, b) => a - b);
const reps = d[0]?.rps_samples?.length ?? 0;

const rows = [];
const spreads = {};
for (const engine of ['postgres', 'mysql']) {
  const nat = NATIVE[engine];
  const layers = [...new Set(d.filter((x) => x.engine === engine).map((x) => x.adapter))]
    .filter((a) => !/-tuned$/.test(a) && a !== nat);
  rows.push(`    \\multicolumn{${fanouts.length + 1}}{l}{\\emph{${ENGINE_LABEL[engine]}}} \\\\`);
  for (const a of layers) {
    const cells = fanouts.map((f) => {
      const n = d.find((x) => x.engine === engine && x.fanout === f && x.adapter === nat);
      const c = d.find((x) => x.engine === engine && x.fanout === f && x.adapter === a);
      return n && c ? (n.rps / c.rps).toFixed(1) : '--';
    });
    rows.push(`    \\quad\\texttt{${a}} & ${cells.join(' & ')} \\\\`);
  }
  const at = (f) => {
    const cs = d.filter((x) => x.engine === engine && x.fanout === f && !/-tuned$/.test(x.adapter));
    const n = cs.find((x) => x.adapter === nat);
    return n ? n.rps / Math.min(...cs.map((x) => x.rps)) : NaN;
  };
  spreads[engine] = [at(fanouts[0]), at(fanouts[fanouts.length - 1])];
}

const fmt = (e) => `$${spreads[e][0].toFixed(1)}\\times$ to $${spreads[e][1].toFixed(1)}\\times$`;
const tex = `% auto-generated by scripts/gen-fanout-table.mjs
\\begin{table}[htbp]
  \\centering
  \\caption{Native-relative throughput multiplier on the deep fetch as the result-graph
    breadth varies from ${fanouts[0]} to ${fanouts[fanouts.length - 1]} child rows
    (median of ${reps} runs per cell, exploratory). A value of $1.0$ is parity with the
    engine's native driver; larger is slower. The multipliers are near-flat on MySQL,
    where the native-relative spread moves ${fmt('mysql')}, but not on PostgreSQL, where
    it widens ${fmt('postgres')}: MikroORM and Sequelize diverge from the native driver
    as breadth grows while Knex and Drizzle converge toward it. The sweep varies breadth
    only, not graph depth, schema, or query mix, so it bounds no other dimension.}
  \\label{tab:fanout}
  \\begin{tabular}{l ${fanouts.map(() => 'r').join(' ')}}
    \\toprule
    Layer & ${fanouts.map((f) => `${f}`).join(' & ')} \\\\
    \\midrule
${rows.join('\n')}
    \\bottomrule
  \\end{tabular}
\\end{table}
`;

await writeFile(join(here, '..', 'results', 'tables', 'fanout.tex'), tex);
await writeFile(join(here, '..', '..', 'paper', 'tables', 'fanout.tex'), tex);
console.log(`PostgreSQL spread ${fmt('postgres')}, MySQL ${fmt('mysql')}`);
console.log('wrote results/tables/fanout.tex + paper/tables/fanout.tex');
