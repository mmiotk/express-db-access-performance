import fs from 'node:fs';
import path from 'node:path';
import {
  blockedInteraction,
  geomMeanRatio,
  pairedBootstrapRatioCI,
} from '../bench/stats.mjs';

const root = path.resolve(import.meta.dirname, '..');
const resultsDir = path.join(root, 'results');
const paperDir = path.resolve(root, '..', 'paper', 'tables');
const correctedPath = path.join(resultsDir, "rq2-campaign2.json");
if (!fs.existsSync(correctedPath)) {
  throw new Error("wait for the corrected-state campaign output");
}

const historical = JSON.parse(fs.readFileSync(path.join(resultsDir, 'raw.json'), 'utf8'));
const corrected = JSON.parse(fs.readFileSync(correctedPath, "utf8"));
const expectedPairs = new Set([
  'pg|postgres', 'pg-tuned|postgres', 'mysql2|mysql', 'mysql2-tuned|mysql',
  ...['knex', 'drizzle', 'prisma', 'sequelize', 'typeorm', 'objection', 'mikroorm']
    .flatMap((adapter) => ['postgres', 'mysql'].map((engine) => adapter + '|' + engine)),
]);
const expectedEndpoints = new Set(['point_read', 'range_scan', 'deep_fetch', 'aggregation', 'write']);
const seen = new Set();
const validationErrors = [];
for (const row of corrected) {
  const pair = row.adapter + '|' + row.engine;
  const key = pair + '|' + row.endpoint;
  if (!expectedPairs.has(pair) || !expectedEndpoints.has(row.endpoint)) validationErrors.push('unexpected cell ' + key);
  if (seen.has(key)) validationErrors.push('duplicate cell ' + key);
  seen.add(key);
  for (const field of ['rps_samples', 'p99_samples', 'p975_samples']) {
    if (!Array.isArray(row[field]) || row[field].length !== 25) validationErrors.push(key + ' has ' + field + ' length ' + (row[field]?.length ?? 'missing'));
  }
  if (row.repeats !== 25 || !row.independent || !row.preflight || !row.paired_streams) validationErrors.push(key + ' has incomplete campaign metadata');
  if (row.errors !== 0 || row.timeouts !== 0 || row.non2xx !== 0) validationErrors.push(key + ' has request failures');
}
for (const pair of expectedPairs) for (const endpoint of expectedEndpoints) { const key = pair + '|' + endpoint; if (!seen.has(key)) validationErrors.push('missing cell ' + key); }
if (corrected.length !== 90) validationErrors.push('expected 90 rows, found ' + corrected.length);
if (validationErrors.length) throw new Error('corrected campaign validation failed:\n- ' + validationErrors.join('\n- '));
fs.writeFileSync(
  path.join(resultsDir, 'rq2-corrected-full.json'),
  JSON.stringify(corrected, null, 2) + '\n',
);
const currentPrimary = corrected;
fs.writeFileSync(
  path.join(resultsDir, "current-primary.json"),
  JSON.stringify(currentPrimary, null, 2) + "\n",
);

const layers = ['knex', 'drizzle', 'prisma', 'sequelize', 'typeorm', 'objection', 'mikroorm'];
const patterns = [
  ['point_read', 'Point read'],
  ['range_scan', 'Range'],
  ['deep_fetch', 'Deep fetch'],
  ['aggregation', 'Aggregation'],
  ['write', 'Insert'],
];
const engines = ['postgres', 'mysql'];
const median = (values) => {
  const xs = [...values].sort((a, b) => a - b);
  const mid = Math.floor(xs.length / 2);
  return xs.length % 2 ? xs[mid] : (xs[mid - 1] + xs[mid]) / 2;
};
const index = (rows) => new Map(rows.map((row) => [
  `${row.adapter}|${row.engine}|${row.endpoint}`,
  row,
]));
const oldIndex = index(historical);
const newIndex = index(corrected);
const samples = (source, layer, engine, endpoint) => {
  const row = source.get(`${layer}|${engine}|${endpoint}`);
  if (!row?.rps_samples?.length) throw new Error(`missing samples: ${layer}/${engine}/${endpoint}`);
  return row.rps_samples;
};
const order = (source, engine, endpoint) => layers
  .map((layer) => ({ layer, value: median(samples(source, layer, engine, endpoint)) }))
  .sort((a, b) => b.value - a.value);
const rankOf = (source, layer, engine, endpoint) =>
  order(source, engine, endpoint).findIndex((row) => row.layer === layer) + 1;
const fmt = (value) => Math.round(value).toLocaleString('en-US').replaceAll(',', '{,}');
const writeBoth = (name, text) => {
  fs.writeFileSync(path.join(resultsDir, 'tables', name), text);
  fs.writeFileSync(path.join(paperDir, name), text);
};

const rankRows = layers.map((layer) => {
  const cells = patterns.flatMap(([endpoint]) =>
    engines.map((engine) => rankOf(newIndex, layer, engine, endpoint)));
  return `    \\texttt{${layer}} & ${cells.join(' & ')} \\\\`;
}).join('\n');
const ranksTex = `% auto-generated by scripts/gen-rq2-corrected-tables.mjs
\\begin{table}[htbp]
  \\centering
  \\caption{Corrected-state throughput ranks (1 = fastest) for the seven portable layers on PostgreSQL (PG) and MySQL. Every cell has 25 paired campaign repetitions, zero request failures, and a passing pre/post state check.}
  \\label{tab:ranks}
  \\begin{adjustbox}{max width=\\textwidth}
  \\begin{tabular}{l cc cc cc cc cc}
    \\toprule
    & \\multicolumn{2}{c}{Point read} & \\multicolumn{2}{c}{Range}
    & \\multicolumn{2}{c}{Deep fetch} & \\multicolumn{2}{c}{Aggregation}
    & \\multicolumn{2}{c}{Insert} \\\\
    \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\\cmidrule(lr){10-11}
    Layer & PG & MySQL & PG & MySQL & PG & MySQL & PG & MySQL & PG & MySQL \\\\
    \\midrule
${rankRows}
    \\bottomrule
  \\end{tabular}
  \\end{adjustbox}
\\end{table}
`;
writeBoth('ranks.tex', ranksTex);

function mulberry32(a) {
  return function rand() {
    a |= 0;
    a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
const interactionRows = layers.map((layer) => {
  const cells = patterns.map(([endpoint], patternIndex) => {
    const pg = samples(newIndex, layer, 'postgres', endpoint);
    const mysql = samples(newIndex, layer, 'mysql', endpoint);
    const ratio = geomMeanRatio(pg, mysql);
    const [lo, hi] = pairedBootstrapRatioCI(pg, mysql, {
      B: 5000,
      level: 0.95,
      rand: mulberry32(0x57a75 + patternIndex * 101 + layers.indexOf(layer)),
    });
    return `${ratio.toFixed(2)}~[${lo.toFixed(2)},${hi.toFixed(2)}]`;
  });
  return `    \\texttt{${layer}} & ${cells.join(' & ')} \\\\`;
}).join('\n');
const interactionTests = patterns.map(([endpoint, label], patternIndex) => {
  const D = layers.map((layer) => {
    const pg = samples(newIndex, layer, 'postgres', endpoint);
    const mysql = samples(newIndex, layer, 'mysql', endpoint);
    return pg.map((value, replicate) => Math.log(value) - Math.log(mysql[replicate]));
  });
  const result = blockedInteraction(D, {
    B: 20000,
    rand: mulberry32(0x41c7e + patternIndex * 1009),
  });
  return {
    endpoint,
    label,
    statistic: 'randomized-block F on paired log throughput ratios',
    permutationUnit: 'layer labels within campaign replicate',
    F: result.F,
    p: result.p,
    permutations: result.B,
    layers: result.L,
    campaignReplicates: result.R,
  };
});
fs.writeFileSync(
  path.join(resultsDir, 'rq2-corrected-interaction-tests.json'),
  JSON.stringify({
    scope: 'Within one corrected-state campaign on one host; not cross-campaign or cross-host evidence.',
    tests: interactionTests,
  }, null, 2) + '\n',
);
const interactionFRow = interactionTests
  .map((test) => test.F.toFixed(1))
  .join(' & ');
const interactionPRow = interactionTests
  .map((test) => test.p.toPrecision(3))
  .join(' & ');
const interactionTex = `% auto-generated by scripts/gen-rq2-corrected-tables.mjs
\\begin{table}[htbp]
  \\centering
  \\small
  \\caption{Corrected-state PostgreSQL\\,$\\div$\\,MySQL backend-stack throughput
    ratio (geometric mean of paired per-replicate ratios, with a within-campaign
    95\\% paired-bootstrap interval) for the seven portable layers. The DBMS,
    official adapter, lower-level driver, and protocol can change together; ratios
    therefore do not identify a pure DBMS effect. The bottom rows report the
    randomized-block F statistic and permutation p value for heterogeneity
    among layer ratios within this campaign (20{,}000 permutations).}
  \\label{tab:interaction}
  \\begin{adjustbox}{max width=\\textwidth}
  \\begin{tabular}{l ccccc}
    \\toprule
    Layer & Point read & Range scan & Deep fetch & Aggregation & Insert \\\\
    \\midrule
${interactionRows}
    \\midrule
    Blocked F & ${interactionFRow} \\\\
    Permutation p & ${interactionPRow} \\\\
    \\bottomrule
  \\end{tabular}
  \\end{adjustbox}
\\end{table}
`;
writeBoth('interaction.tex', interactionTex);

const records = [];
for (const [endpoint] of patterns) {
  for (const engine of engines) {
    for (const layer of layers) {
      const before = median(samples(oldIndex, layer, engine, endpoint));
      const after = median(samples(newIndex, layer, engine, endpoint));
      records.push({
        endpoint,
        historicalEligible: !(engine === 'mysql' && ['range_scan', 'aggregation', 'write'].includes(endpoint)),
        engine,
        layer,
        historicalRps: before,
        correctedRps: after,
        correctedToHistorical: after / before,
        historicalRank: rankOf(oldIndex, layer, engine, endpoint),
        correctedRank: rankOf(newIndex, layer, engine, endpoint),
      });
    }
  }
}
const transfer = patterns.map(([endpoint]) => ({
  endpoint,
  historical: Object.fromEntries(engines.map((engine) => {
    const top = order(oldIndex, engine, endpoint)[0];
    return [engine, { leader: top.layer, rps: top.value }];
  })),
  corrected: Object.fromEntries(engines.map((engine) => {
    const top = order(newIndex, engine, endpoint)[0];
    return [engine, { leader: top.layer, rps: top.value }];
  })),
}));
fs.writeFileSync(path.join(resultsDir, 'rq2-historical-provenance-comparison.json'), JSON.stringify({
  note: 'Historical provenance comparison only. Historical MySQL range_scan, aggregation, and write cells failed the revised state-admission standard and are ineligible as replication evidence; campaigns are not paired across dates.',
  correctedRows: corrected.length,
  records,
  transfer,
}, null, 2) + '\n');

