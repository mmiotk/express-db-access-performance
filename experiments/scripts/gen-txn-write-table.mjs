// Deterministically rebuild the transactional-write supplement table from its measurement.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const results = join(here, '..', 'results');
const data = JSON.parse(await readFile(join(results, 'txn-write.json'), 'utf8'));
const rows = data.map((row) =>
  `    \\texttt{${row.adapter}} & ${row.rps} & ${row.p99} \\\\`
).join('\n');
const sorted = [...data].sort((a, b) => b.rps - a.rps);
const spread = sorted.length > 1 ? (sorted[0].rps / sorted.at(-1).rps).toFixed(2) : '--';
const reps = Math.max(...data.map((row) => row.rps_samples?.length ?? 0)) || 1;

const tex = `% auto-generated by scripts/gen-txn-write-table.mjs from results/txn-write.json
\\begin{table}[htbp]
  \\centering
  \\caption{Transactional write throughput (req/s) and tail latency (p99, ms) for
    \\texttt{POST /threads}, which inserts a post and five comments in a single
    transaction, on PostgreSQL under default durability (50 connections, median of
    ${reps} runs). A representative layer of each tier is shown; the full matrix is
    outside this sensitivity check. Across the declared subset, the observed throughput
    spread is $${spread}\\times$. This exploratory PostgreSQL subset does not support
    a general claim about writes.}
  \\label{tab:txn_write}
  \\begin{tabular}{l r r}
    \\toprule
    Layer & req/s & p99 (ms) \\\\
    \\midrule
${rows}
    \\bottomrule
  \\end{tabular}
\\end{table}
`;

await writeFile(join(results, 'tables', 'txn_write.tex'), tex);
await writeFile(join(here, '..', '..', 'paper', 'tables', 'txn_write.tex'), tex);
console.log('wrote txn_write.tex from results/txn-write.json');
