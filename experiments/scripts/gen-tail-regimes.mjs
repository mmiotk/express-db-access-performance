// Generate the main-text tail-regime contrast table (tab:tail_regimes) that puts
// the two p99 readings side by side per layer and engine: the high-load p99 under
// equal closed-loop demand (the 50-connection deep-fetch cell of the primary matrix,
// results/current-primary.json by default) versus the coordinated-omission-corrected p99 at matched 50%
// utilization (results/utilization-corrected.{engine}.json). The point of the table is the
// contrast: the wide high-load ladder contracts once each layer is driven at the same nominal fraction of estimated capacity. The contrast is consistent with a material capacity/queueing contribution; it is not a causal decomposition. Regenerates from the
// same raw data as tab:deep_fetch (identical .p99 field) and Supplement Tables S21/S22.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const R = (f) => readFile(join(here, '..', 'results', f), 'utf8').then(JSON.parse);
const out = async (name, tex) => {
  await writeFile(join(here, '..', 'results', 'tables', name), tex);
  await writeFile(join(here, '..', '..', 'paper', 'tables', name), tex);
};

const rawFile = process.env.RAW_FILE ?? 'current-primary.json';
const raw = await R(rawFile);
const utilPgFile = process.env.UTIL_PG_FILE || 'utilization-corrected.postgres.json';
const utilMyFile = process.env.UTIL_MY_FILE || 'utilization-corrected.mysql.json';
const uPg = await R(utilPgFile);
const uMy = await R(utilMyFile);

const ORDER = ['pg', 'mysql2', 'knex', 'drizzle', 'prisma', 'sequelize', 'typeorm', 'objection', 'mikroorm'];
const CAT = {
  pg: 'native-driver', mysql2: 'native-driver', knex: 'query-builder',
  drizzle: 'orm', prisma: 'orm', sequelize: 'orm', typeorm: 'orm', objection: 'orm', mikroorm: 'orm',
};

// High-load p99 (equal closed-loop demand): the deep-fetch cell of the primary matrix.
const demand = (a, eng) => {
  const r = raw.find((x) => x.adapter === a && x.endpoint === 'deep_fetch' && x.engine === eng);
  return r ? String(r.p99) : '--';
};
// Matched 50% utilization p99 (coordinated-omission-corrected open-loop).
const matched = (a, arr) => {
  const r = arr.find((x) => x.adapter === a && x.fraction === 0.5);
  return r ? String(r.p99_med) : '--';
};
const numericRange = (values) => {
  const xs = values.filter((value) => value !== '--').map(Number);
  return Math.min(...xs) + '--' + Math.max(...xs);
};
const demandPgRange = numericRange(ORDER.map((a) => demand(a, 'postgres')));
const matchedPgRange = numericRange(ORDER.map((a) => matched(a, uPg)));
const demandMyRange = numericRange(ORDER.map((a) => demand(a, 'mysql')));
const matchedMyRange = numericRange(ORDER.map((a) => matched(a, uMy)));

const rows = ORDER.map((a) =>
  `    \\texttt{${a}} & ${CAT[a]} & ${demand(a, 'postgres')} & ${matched(a, uPg)} & ${demand(a, 'mysql')} & ${matched(a, uMy)} \\\\`
).join('\n');

const tex = `% auto-generated by scripts/gen-tail-regimes.mjs from the selected primary data + utilization.{engine}.json
\\begin{table}[htbp]
  \\centering
  \\caption{The deep-fetch tail read two ways, per layer and engine. \\emph{Equal demand}
    is the high-load response-time p99 (ms) at the fixed 50-connection closed-loop point --- the
    headline deep-fetch p99, which at this saturating load largely tracks
    capacity and connection-acquisition queueing. \\emph{50\\% util.} is the
    coordinated-omission-corrected p99 when each layer is instead offered half of its
    $\\widehat C_{50}$ capacity proxy (Supplement Tables~S21--S22; denominator sensitivity,
    Table~S45). In this campaign the equal-demand and 50\\%-utilization ranges are
    ${demandPgRange} and ${matchedPgRange}~ms on PostgreSQL, and ${demandMyRange} and
    ${matchedMyRange}~ms on MySQL. The contraction at this stable sub-saturation target is
    consistent with capacity and connection-acquisition queueing contributing materially to
    the high-load gap; it does not establish a deployment-general latency bound.}
  \\label{tab:tail_regimes}
  \\begin{adjustbox}{max width=\\textwidth}
  \\begin{tabular}{l l r r r r}
    \\toprule
    & & \\multicolumn{2}{c}{PostgreSQL p99 (ms)} & \\multicolumn{2}{c}{MySQL p99 (ms)} \\\\
    \\cmidrule(lr){3-4}\\cmidrule(lr){5-6}
    Layer & Category & equal demand & 50\\% util. & equal demand & 50\\% util. \\\\
    \\midrule
${rows}
    \\bottomrule
  \\end{tabular}
  \\end{adjustbox}
\\end{table}
`;

await out('tail_regimes.tex', tex);
console.log('wrote tail_regimes.tex');
